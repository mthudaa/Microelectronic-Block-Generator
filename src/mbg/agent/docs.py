"""Generated reference for the agent tools (docs/TOOLS.md).

``mbg tools --format md`` prints it; ``scripts/sync_agent_tools.py`` writes
it and the validator fails when the committed copy is stale, so the
documentation cannot drift from the registry.
"""
from __future__ import annotations

from mbg.agent import registry


def _type(p) -> str:
    t = p.get("type", "")
    t = "/".join(t) if isinstance(t, list) else t
    if t == "array":
        t = f"{(p.get('items') or {}).get('type', 'any')}[]"
    if p.get("enum"):
        t += " (" + "|".join(map(str, p["enum"])) + ")"
    return t


def tools_markdown() -> str:
    lines = [
        "<!-- GENERATED by `mbg tools --format md` (scripts/sync_agent_tools.py). Do not edit. -->",
        "# MBG agent tools",
        "",
        "Every command prints exactly one JSON envelope on stdout "
        "(`schema: mbg.result/1`):",
        "",
        "| field | meaning |",
        "| :--- | :--- |",
        "| `ok` | `false` only when the tool itself failed (bad input, crash); see `error` |",
        "| `status` | verdict on the design: `PASS`, `FAIL`, `PARTIAL`, `NOT RUN`, `NOT AVAILABLE` |",
        "| `summary` | one line to act on |",
        "| `metrics` | small numbers (full data stays on disk) |",
        "| `artifacts` | paths: GDS, reports, CSV, logs |",
        "| `issues` | `{code, severity, message, hint}`, errors first, at most 20 |",
        "| `next` | suggested next commands |",
        "| `job` | for long tools still running: `{id, state}` -> `mbg job wait <id>` |",
        "",
        "Exit codes: 0 PASS, 1 FAIL/PARTIAL, 2 usage error, 3 NOT RUN/NOT AVAILABLE, "
        "4 still running. Numbers accept SPICE suffixes (`20u`, `1p`). Objects are "
        "inline JSON or a path to a `.json` file. Any tool also takes "
        "`--args-json '{...}'`.",
        "",
        "Over MCP (`scripts/mbg mcp`) the same tools are published with "
        "underscores; tools sharing a group are one MCP tool with a selector "
        "(`pdk` action=list|info, `design` action=init|status, `verify` "
        "check=drc|lvs|pex, `job` action=status|wait|cancel).",
        "",
    ]
    for group, tools in registry.groups().items():
        for t in tools:
            lines.append(f"## `{t.cli}`")
            lines.append("")
            lines.append(t.summary + (" *(long: runs as a background job)*" if t.long else ""))
            lines.append("")
            props = t.schema.get("properties", {})
            req = set(t.schema.get("required", []))
            pos = t.schema.get("x-positional", [])
            if props:
                lines.append("| argument | type | description |")
                lines.append("| :--- | :--- | :--- |")
                for name, p in props.items():
                    flag = f"`<{name}>` / `--{name.replace('_', '-')}`" if name in pos \
                        else f"`--{name.replace('_', '-')}`"
                    star = " **(required)**" if name in req else ""
                    desc = p.get("description", "").replace("|", "\\|")
                    lines.append(f"| {flag} | {_type(p)} | {desc}{star} |")
                lines.append("")
            for ex in t.examples:
                lines.append(f"    {ex}")
            if t.examples:
                lines.append("")
    return "\n".join(lines).rstrip() + "\n"
