"""Self-starting relaxation-oscillator temperature sensor — gf180mcuD, 3.3 V.

Ports: VDD VSS TEMP_OUT exactly.  No CLK/START/ENABLE/RESET/IBIAS/VBIAS/TRIM,
no external reference current, no forced initial condition anywhere.

Topology (flat, one .subckt, 18 MOS + 2 native passives)
--------------------------------------------------------
1. Beta-multiplier (constant-gm) bias, degenerated by a native ``ppolyf_u``
   poly resistor.  Its current is
       I = (2 / (mu_n Cox (W/L)_N1)) * (1 - 1/sqrt(K))^2 / R^2
   The gf180 poly resistor is essentially temperature-flat (r_tc1 = -0.9e-4,
   r_tc2 = 7e-7 -> under 1 % over -40..125 C), so the temperature coefficient
   of I is set almost entirely by 1/mu_n(T), i.e. strongly PTAT.  That is the
   sensing mechanism: drift with temperature is the signal here, not the error.

2. Self-start: XMS1/XMS2/XMS3 form a self-extinguishing starter.  XMS1 is a
   near-minimum-strength always-on PMOS that pulls nsu high while the bias is
   dead; XMS3 then drags the PMOS mirror gate nbp down and current begins.
   Once nb1 has risen, XMS2 clamps nsu low and XMS3 switches off, so the
   starter perturbs neither mirror ratio in steady state.  The zero-current
   state of the beta-multiplier is therefore not a stable operating point of
   the powered-up circuit, and no external pulse or .ic is used.

3. Timing core: the PTAT current charges a native metal4/metal5 MIM
   (``cap_mim_2f0_m4m5_noshield``).  XMPC sources I continuously; XMNS gates a
   2*I sink (XMNC), so the node ramps at +I/C while TEMP_OUT is low and -I/C
   while TEMP_OUT is high.  Equal up/down slopes give a naturally ~50 % duty
   cycle with one switch instead of two.

4. Six-transistor CMOS Schmitt trigger on the ramp node sets the two
   thresholds; its hysteresis window dV is the second term in
       f = I / (2 C dV).

5. A CMOS inverter buffers the Schmitt output to TEMP_OUT rail-to-rail and
   closes the loop by driving the discharge switch.

Structural metrics: 18 MOS, 2 passives, 12 nets.
"""

# ── bias generator ────────────────────────────────────────────────────
L_BIAS = 4.0        # bias-branch channel length [um]
WP_BIAS = 4.0       # beta-multiplier PMOS mirror width [um]
WN_BIAS = 1.0       # beta-multiplier NMOS reference (1x) width [um].
                    # W/L = 0.25 puts XMN1 in strong inversion at ~9 uA,
                    # which is what makes the reference current track
                    # 1/mu_n (ute = -1.568 -> +5200 ppm/C) instead of the
                    # weaker moderate-inversion PTAT of a wider device.
K_MULT = 4.0        # beta-multiplier width ratio  (W_N2 = K * W_N1)
R_W = 1.0           # poly-resistor width  [um]  (PRES.1 minimum is 0.80)
R_L = 100.0         # poly-resistor length [um]  -> ~37 kohm at 350 ohm/sq

# ── self-start branch ─────────────────────────────────────────────────
WSU1, LSU1 = 0.6, 9.5      # weak always-on pull-up.  W=0.22 (the PDK
                           # minimum) is not buildable: glayout cannot fit a
                           # source/drain via array on it (dim 0.28 < 0.46).
WSU2, LSU2 = 4.0, 0.6      # shut-off device (gate = nb1)
WSU3, LSU3 = 1.0, 1.0      # kick device (pulls nbp down)

# ── timing core ───────────────────────────────────────────────────────
WPC = 4.0           # charge current source (mirrors XMP1)
WNC = 2.0           # discharge sink, 2x the mirror -> net -I when switched in
WSW, LSW = 4.0, 0.6  # discharge switch
C_SIZE = 34.0       # MIM plate edge [um] -> ~2.33 pF at 1.99 fF/um^2

# ── Schmitt trigger ───────────────────────────────────────────────────
L_SCH = 4.0         # long channels: the Schmitt sees a slow ramp, so its
                    # series stacks conduct crowbar current continuously; the
                    # channel length is what bounds that current.
WSP1 = 2.0          # PMOS series pair
WSP3 = 4.0          # PMOS feedback  -> sets the falling threshold
WSN1 = 1.0          # NMOS series pair
WSN3 = 2.0          # NMOS feedback  -> sets the rising threshold

# ── output buffer ─────────────────────────────────────────────────────
L_BUF = 1.0
WBP, WBN = 6.0, 3.0

CELL = "temp_sensor"


def temp_sensor_netlist(l_bias=L_BIAS, wp_bias=WP_BIAS, wn_bias=WN_BIAS,
                        k_mult=K_MULT, r_w=R_W, r_l=R_L,
                        wpc=WPC, wnc=WNC, wsw=WSW, lsw=LSW, c_size=C_SIZE,
                        l_sch=L_SCH, wsp1=WSP1, wsp3=WSP3,
                        wsn1=WSN1, wsn3=WSN3,
                        l_buf=L_BUF, wbp=WBP, wbn=WBN,
                        wsu1=WSU1, lsu1=LSU1, wsu2=WSU2, lsu2=LSU2,
                        wsu3=WSU3, lsu3=LSU3):
    """Build the flat temp_sensor subcircuit."""
    wn2 = wn_bias * k_mult
    L = []
    a = L.append
    a("* Self-starting relaxation-oscillator temperature sensor, gf180mcuD 3.3V")
    a("* Ports: VDD VSS TEMP_OUT.  Internal PTAT beta-multiplier reference,")
    a("* native ppolyf_u degeneration resistor + metal4/metal5 MIM timing cap.")
    a("* Self-start: XMS1/XMS2/XMS3, self-extinguishing.  No .ic, no stimulus.")
    a('.lib "{PDK_LIB}" typical')
    a(f".subckt {CELL} VDD VSS TEMP_OUT")
    a("* --- beta-multiplier PTAT current reference ---")
    a(f"XMP1 nb1 nbp VDD VDD pfet_03v3 L={l_bias:g}u W={wp_bias:g}u nf=1")
    a(f"XMP2 nbp nbp VDD VDD pfet_03v3 L={l_bias:g}u W={wp_bias:g}u nf=1")
    a(f"XMN1 nb1 nb1 VSS VSS nfet_03v3 L={l_bias:g}u W={wn_bias:g}u nf=1")
    a(f"XMN2 nbp nb1 nrs VSS nfet_03v3 L={l_bias:g}u W={wn2:g}u nf=1")
    # Third terminal = the p-substrate the resistor sits in, which the
    # substrate taps hold at VSS.  Magic extracts ppolyf_u with that pin, so
    # leaving it off the schematic makes netgen invent a proxy net and the
    # LVS fails on net count (12 vs 13) even though every device matches.
    a(f"XR1  nrs VSS VSS ppolyf_u W={r_w:g}u L={r_l:g}u")
    a("* --- self-extinguishing start-up branch ---")
    a(f"XMS1 nsu VSS VDD VDD pfet_03v3 L={lsu1:g}u W={wsu1:g}u nf=1")
    a(f"XMS2 nsu nb1 VSS VSS nfet_03v3 L={lsu2:g}u W={wsu2:g}u nf=1")
    a(f"XMS3 nbp nsu VSS VSS nfet_03v3 L={lsu3:g}u W={wsu3:g}u nf=1")
    a("* --- native-passive relaxation timing core ---")
    a(f"XMPC ncap nbp VDD VDD pfet_03v3 L={l_bias:g}u W={wpc:g}u nf=1")
    a(f"XMNS ncap TEMP_OUT nsk VSS nfet_03v3 L={lsw:g}u W={wsw:g}u nf=1")
    a(f"XMNC nsk nb1 VSS VSS nfet_03v3 L={l_bias:g}u W={wnc:g}u nf=1")
    a(f"XC1  ncap VSS cap_mim_2f0_m4m5_noshield W={c_size:g}u L={c_size:g}u")
    a("* --- hysteresis comparator (6T CMOS Schmitt trigger) ---")
    a(f"XMSP1 npa ncap VDD VDD pfet_03v3 L={l_sch:g}u W={wsp1:g}u nf=1")
    a(f"XMSP2 nst ncap npa VDD pfet_03v3 L={l_sch:g}u W={wsp1:g}u nf=1")
    a(f"XMSP3 VSS nst npa VDD pfet_03v3 L={l_sch:g}u W={wsp3:g}u nf=1")
    a(f"XMSN1 nnb ncap VSS VSS nfet_03v3 L={l_sch:g}u W={wsn1:g}u nf=1")
    a(f"XMSN2 nst ncap nnb VSS nfet_03v3 L={l_sch:g}u W={wsn1:g}u nf=1")
    a(f"XMSN3 VDD nst nnb VSS nfet_03v3 L={l_sch:g}u W={wsn3:g}u nf=1")
    a("* --- output buffer, closes the loop and drives TEMP_OUT ---")
    a(f"XMB1 TEMP_OUT nst VDD VDD pfet_03v3 L={l_buf:g}u W={wbp:g}u nf=1")
    a(f"XMB2 TEMP_OUT nst VSS VSS nfet_03v3 L={l_buf:g}u W={wbn:g}u nf=1")
    a(".ends")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    print(temp_sensor_netlist(), end="")
